package be.elevenways.hohenheim.server.build;

import be.elevenways.hohenheim.model.BuildOperationModel;
import be.elevenways.hohenheim.server.docker.PinnedImages;
import be.elevenways.hohenheim.server.util.FileTrees;
import be.elevenways.hohenheim.server.util.Json;
import org.checkerframework.checker.nullness.qual.NonNull;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.attribute.FileTime;
import java.util.List;
import java.util.regex.Pattern;

/**
 * The static site builder kind: it writes a multi-stage Dockerfile into the build context (the site's build command
 * in a build stage, then its output folder copied into the pinned static server), after which the Dockerfile
 * builder runs it unchanged in the same sandbox on the workload host.
 *
 * AIDEV-NOTE: the release serves on {@link #PORT} with {@code /health} answering the release engine's probe and
 * dotfiles hidden, so a site whose output folder is the repository root never serves its {@code .git} or the
 * generated Dockerfile. Every value the Dockerfile carries is judged here first: folders are plain relative paths,
 * the build image a plain reference, and the command travels JSON-quoted in exec form, never spliced into a line.
 *
 * @author Jelle De Loecker
 * @since  0.10.0
 */
public final class StaticSiteBuilder implements Builders {

    /** The port the static server listens on inside the release. */
    public static final int PORT = 8080;

    /** The path the static server answers its health on. */
    public static final String HEALTH_PATH = "/health";

    /** Where the generated Dockerfile lands, relative to the build context. */
    static final String EMIT_DIR = ".hohenheim-static";
    static final String EMITTED_DOCKERFILE = EMIT_DIR + "/Dockerfile";

    /** Where the build stage holds the checkout. */
    private static final String SOURCE_ROOT = "/site";

    /** A folder inside the repository: plain relative segments, no parent steps. */
    private static final Pattern RELATIVE_FOLDER = Pattern.compile("[A-Za-z0-9_.-]+(/[A-Za-z0-9_.-]+)*/?");

    /** An image reference: registry, path, tag and digest characters only. */
    private static final Pattern IMAGE_REFERENCE = Pattern.compile("[A-Za-z0-9][A-Za-z0-9._/:@-]*");

    @Override
    public @NonNull String kind() {
        return BuildOperationModel.KIND_STATIC;
    }

    @Override
    public @NonNull BuildPlan plan(@NonNull BuildRequest request, int buildId, @NonNull BuildLog log,
                                   @NonNull BuildSandbox sandbox) throws IOException {
        BuildRequest.StaticSite site = request.site();
        String output = folder(site.outputDirectory(), "output folder");
        String dockerfile = dockerfile(site, output);

        // Stale output of a previous build in a reused checkout slot never leaks into this one.
        FileTrees.deleteQuietly(request.contextDir().resolve(EMIT_DIR));
        Path emitted = request.contextDir().resolve(EMITTED_DOCKERFILE);
        Files.createDirectories(emitted.getParent());
        Files.writeString(emitted, dockerfile, StandardCharsets.UTF_8);
        // Epoch mtimes, as the nixpacks emit: the generated file must not move the digest of an unchanged site.
        Files.setLastModifiedTime(emitted, FileTime.fromMillis(0));
        Files.setLastModifiedTime(emitted.getParent(), FileTime.fromMillis(0));
        log.line("[hohenheim] static site: " + (site.buildCommand().isBlank()
            ? "serving " + shown(output) + " as it is" : "building, then serving " + shown(output))
            + ", generated " + EMITTED_DOCKERFILE);

        BuildRequest derived = new BuildRequest(request.forModel(), request.forId(), request.builderKind(),
            request.contextDir(), EMITTED_DOCKERFILE, request.tag(), request.buildArgs(), request.sourceRef(),
            request.registry(), request.quota());
        return new DockerfileBuilder().plan(derived, buildId, log, sandbox);
    }

    /** The unprivileged user (nobody:nogroup) the serving stage runs as. */
    static final String SERVING_USER = "65534:65534";

    /**
     * @return the Dockerfile serving {@code output}, built first when the site names a build command
     * @throws IOException naming the value that cannot go into a Dockerfile
     */
    static @NonNull String dockerfile(BuildRequest.@NonNull StaticSite site, @NonNull String output)
            throws IOException {
        StringBuilder text = new StringBuilder("# Generated by Hohenheim for a static site; rewritten on every build.\n");
        String copy;
        if (site.buildCommand().isBlank()) {
            copy = "COPY " + Json.stringify(List.of(output, "/public/")) + "\n";
        } else {
            String image = site.buildImage().isBlank() ? PinnedImages.NODE_BUILD : site.buildImage().trim();
            if (!IMAGE_REFERENCE.matcher(image).matches()) {
                throw new IOException("REFUSED to build: the build image '" + image + "' is not an image reference");
            }
            String workdir = folder(site.buildDirectory(), "build folder");
            text.append("FROM ").append(image).append(" AS build\n")
                .append("COPY . ").append(SOURCE_ROOT).append("\n")
                .append("WORKDIR ").append(inSource(workdir)).append("\n")
                .append("RUN ").append(Json.stringify(List.of("/bin/sh", "-c", site.buildCommand().trim())))
                .append("\n");
            copy = "COPY --from=build " + Json.stringify(List.of(inSource(output), "/public/")) + "\n";
        }
        return text.append("FROM ").append(PinnedImages.STATIC_WEB_SERVER).append("\n")
            .append("ENV SERVER_PORT=").append(PORT).append(" SERVER_ROOT=/public SERVER_HEALTH=true")
            .append(" SERVER_IGNORE_HIDDEN_FILES=true\n")
            .append(copy)
            // Served as nobody: the server only reads the copied files and listens above 1024, so it never needs
            // root, and a shell into it is an unprivileged one.
            .append("USER ").append(SERVING_USER).append("\n")
            .toString();
    }

    /** @return a folder of the repository as the build stage holds it (a directory COPY copies its contents) */
    private static @NonNull String inSource(@NonNull String folder) {
        return Path.of(SOURCE_ROOT, folder).normalize().toString();
    }

    /**
     * @return the folder as a relative path without its trailing slash, "." for a blank one (the repository root)
     * @throws IOException for an absolute path, a parent step or a character a Dockerfile would read otherwise
     */
    static @NonNull String folder(@NonNull String declared, @NonNull String what) throws IOException {
        String folder = declared.trim();
        while (folder.startsWith("./")) {
            folder = folder.substring(2);
        }
        if (folder.isEmpty() || folder.equals(".") || folder.equals("/")) {
            return ".";
        }
        if (!RELATIVE_FOLDER.matcher(folder).matches() || List.of(folder.split("/")).contains("..")) {
            throw new IOException("REFUSED to build: the " + what + " '" + declared.trim()
                + "' is not a folder inside the repository (letters, digits, '.', '_', '-' and '/' only)");
        }
        return folder.endsWith("/") ? folder.substring(0, folder.length() - 1) : folder;
    }

    private static @NonNull String shown(@NonNull String folder) {
        return folder.equals(".") ? "the repository root" : "'" + folder + "'";
    }
}
